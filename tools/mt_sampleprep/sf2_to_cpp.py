"""
sf2_to_cpp.py -- turn the compressed Mellotron SF2 files into the C++ sample
bank the engine links against.

Reads every multi-sample SF2 in --src (one instrument each, as written by
compress_sf2.py) and writes into instruments/PicoFaceMT/src/data/

    mello_<id>.cpp   16-bit mono PCM of one instrument + its zone table
    mello_data.h     declarations shared by the generated files
    mello_bank.cpp   the bank table (mello::kBank / mello::kBankSize)

A file with a single recording shorter than a second is the key click: it
goes into mello_click.cpp, unchanged, and the engine plays it at every
key-down. Other single-recording files (a gong) are skipped unless --all is
given.
instrument.cmake lists the generated files by name; a changed set of
instruments has to be entered there.

    python3 tools/mt_sampleprep/sf2_to_cpp.py --src /path/to/compressed
"""
import os, re, sys, glob, argparse
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import compress_sf2 as sf2          # noqa: E402  (SF2 reader)

SPDX = ("// SPDX-License-Identifier: GPL-3.0-or-later\n"
        "// SPDX-FileCopyrightText: 2026 Michi71\n"
        "//\n// Generated by tools/mt_sampleprep/sf2_to_cpp.py -- do not edit.\n\n")
# The recordings are not this project's work: they are licensed CC BY 4.0, which
# asks for credit, a link to the licence and a note of what was changed. Every
# generated PCM file carries that; the bank table and declarations are code.
CREDIT = "Taijiguy, Mellotron M400S serial #500 (1973)"
PCM_NOTICE = ("// SPDX-License-Identifier: CC-BY-4.0\n"
              "//\n"
              "// Recordings: {credit}.\n"
              "// Licensed under Creative Commons Attribution 4.0 International,\n"
              "// https://creativecommons.org/licenses/by/4.0/\n"
              "// Changed for PicoFaceMT: each recording cut to its attack plus a\n"
              "// crossfaded loop, and one recording kept per three keys\n"
              "// (tools/mt_sampleprep). Provided without warranty.\n"
              "//\n// Generated by tools/mt_sampleprep/sf2_to_cpp.py -- do not edit.\n\n")
CLICK_NOTICE = ("// SPDX-License-Identifier: CC-BY-4.0\n"
                "//\n"
                "// Recording: {credit}.\n"
                "// Licensed under Creative Commons Attribution 4.0 International,\n"
                "// https://creativecommons.org/licenses/by/4.0/\n"
                "// Unchanged. Provided without warranty.\n"
                "//\n// Generated by tools/mt_sampleprep/sf2_to_cpp.py -- do not edit.\n\n")
GUARD = 4      # samples appended after a one-shot so interpolation may read ahead


# Panel names. The value cell of the panel is 50 pixels wide, which is eight
# characters of its small face (five of the bold one), so the model prefix
# goes and what is still too long gets a short form here.
LABEL_MAX = 8
LABELS = {
    "Gc3 Brass": "Gc3Brass",
    "M300A Violins": "M300A Vn",
    "M300B Violin": "M300B Vn",
    "M400 Cmb Choir": "Choir",
    "M400 String Section": "Strings",
    "M400 Woodwind2": "Woodwind",
    "MKII 3 Violins": "3Violins",
}


def label(name):
    short = LABELS.get(name)
    if short is None:
        short = name
        for prefix in ("M400 ", "MKII "):
            if name.startswith(prefix):
                short = name[len(prefix):]
    if len(short) > LABEL_MAX:
        sys.exit(f"{name}: panel name '{short}' is longer than {LABEL_MAX} characters, "
                 "add a short form to LABELS")
    return short


def ident(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def convert(path):
    f = sf2.read_sf2(path)
    zones = []
    for z in f["zones"]:
        kr, sid, _rest = sf2.zone_parts(z)
        if sid is None:
            continue
        modes = dict(z["gens"]).get(sf2.G_SAMPLEMODES, 0)
        zones.append((kr or (0, 127), sid, modes & 1))
    zones.sort()
    rates = {f["samples"][sid]["sr"] for _, sid, _ in zones}
    assert len(rates) == 1, f"{path}: mixed sample rates"
    pcm, table, placed = [], [], {}
    pos = 0
    for (lo, hi), sid, looped in zones:
        s = f["samples"][sid]
        if sid not in placed:
            d = s["data"].astype(np.int16)
            if not looped:
                d = np.concatenate([d, np.zeros(GUARD, np.int16)])
            placed[sid] = pos
            pcm.append(d)
            pos += len(d)
        st = placed[sid]
        n = len(s["data"])
        ls, le = s["loop"] if looped else (n, n)
        table.append((lo, hi, s["key"], s["corr"], st, st + n, st + ls, st + le))
    return dict(rate=rates.pop(), pcm=np.concatenate(pcm), zones=table, recordings=len(placed))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", required=True, help="directory with the compressed SF2 files")
    ap.add_argument("--out", default=os.path.join(ROOT, "instruments", "PicoFaceMT", "src", "data"))
    ap.add_argument("--credit", default=CREDIT, help="attribution written into the PCM files")
    ap.add_argument("--all", action="store_true", help="include single-sample files")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for old in glob.glob(os.path.join(a.out, "mello_*")):
        os.remove(old)

    bank, total, click = [], 0, None
    for path in sorted(glob.glob(os.path.join(a.src, "*.sf2"))):
        name = os.path.basename(path)[:-4]
        inst = convert(path)
        if inst["recordings"] == 1 and len(inst["pcm"]) < inst["rate"] and click is None:
            click = (name, inst)
            print(f"click {name} ({len(inst['pcm'])} samples, {inst['rate']} Hz)")
            continue
        if inst["recordings"] < 2 and not a.all:
            print(f"skip  {name} (single sample)")
            continue
        iid = ident(name)
        with open(os.path.join(a.out, f"mello_{iid}.cpp"), "w") as fh:
            fh.write(PCM_NOTICE.format(credit=a.credit) + '#include "mello_data.h"\n\nnamespace mello {\n\n')
            fh.write(f"// {name}: {len(inst['pcm'])} samples, {inst['rate']} Hz\n")
            fh.write(f"const int16_t kPcm_{iid}[] = {{\n")
            p = inst["pcm"]
            for i in range(0, len(p), 16):
                fh.write(" " + ",".join(str(int(v)) for v in p[i:i + 16]) + ",\n")
            fh.write("};\n\n// keyLo keyHi root cents start end loopStart loopEnd\n")
            fh.write(f"const Zone kZones_{iid}[] = {{\n")
            for z in inst["zones"]:
                fh.write("    {" + ", ".join(str(v) for v in z) + "},\n")
            fh.write("};\n\n}  // namespace mello\n")
        bank.append((name, iid, inst))
        total += len(inst["pcm"]) * 2
        print(f"ok    {name:22s} {len(inst['zones']):2d} zones {len(inst['pcm']) * 2 / 1024:6.0f} kB")

    # The key click. Without one the engine still links: the length is zero.
    with open(os.path.join(a.out, "mello_click.cpp"), "w") as fh:
        pcm = click[1]["pcm"][:-GUARD] if click else np.zeros(0, np.int16)
        fh.write((CLICK_NOTICE.format(credit=a.credit) if click else SPDX)
                 + '#include "mello/bank.h"\n\nnamespace mello {\n\n')
        fh.write(f"// {click[0] if click else 'no key click in this set'}\n")
        fh.write("const int16_t kClickPcm[] = {\n")
        for i in range(0, len(pcm), 16):
            fh.write(" " + ",".join(str(int(v)) for v in pcm[i:i + 16]) + ",\n")
        fh.write(" 0,\n};\n")                  # one sample for interpolation to read ahead
        fh.write(f"const uint32_t kClickLength = {len(pcm)};\n")
        fh.write(f"const uint32_t kClickRate = {click[1]['rate'] if click else 44100};\n")
        fh.write("\n}  // namespace mello\n")

    with open(os.path.join(a.out, "mello_data.h"), "w") as fh:
        fh.write(SPDX + '#pragma once\n#include "mello/bank.h"\n\nnamespace mello {\n')
        for _, iid, _ in bank:
            fh.write(f"extern const int16_t kPcm_{iid}[];\nextern const Zone kZones_{iid}[];\n")
        fh.write("}  // namespace mello\n")
    with open(os.path.join(a.out, "mello_bank.cpp"), "w") as fh:
        fh.write(SPDX + '#include "mello_data.h"\n\nnamespace mello {\n\n')
        fh.write("const Instrument kBank[] = {\n")
        for name, iid, inst in bank:
            fh.write(f'    {{"{name}", "{label(name)}", kPcm_{iid}, kZones_{iid}, {len(inst["zones"])}, {inst["rate"]}}},\n')
        fh.write(f"}};\nconst int kBankSize = {len(bank)};\n\n}}  // namespace mello\n")
    print(f"bank: {len(bank)} instruments, {total / 1e6:.2f} MB PCM")


if __name__ == "__main__":
    main()
