"""Embed the user's own SysEx banks into the PicoFaceVS image.

Usage: embed_banks.py ROMS_DIR OUT_HEADER

Collects every .syx file in ROMS_DIR and writes them, concatenated, into a C
header as one byte array. The firmware hands that array to the engine's SysEx
loaders at start-up, which pick out what they know (a Prophet VS program bank
or single programs, a Behringer Pro VS Mini patch bank) and ignore the rest.
Without any .syx the array is empty and the instrument starts with the init
program only; banks can then still be sent over MIDI.

The header is written to the build directory. It contains the user's files and
must never be committed.
"""
import os
import sys

roms, out = sys.argv[1], sys.argv[2]
data, names = bytearray(), []
if os.path.isdir(roms):
    for name in sorted(os.listdir(roms)):
        if name.lower().endswith('.syx'):
            data += open(os.path.join(roms, name), 'rb').read()
            names.append(name)
lines = ["// Generated by tools/vs_data/embed_banks.py - do not edit, do not commit.",
         "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
         f"// {', '.join(names) if names else 'no .syx files found'}",
         f"inline constexpr size_t kVsEmbeddedBankSize = {len(data)};",
         f"inline constexpr uint8_t kVsEmbeddedBanks[{max(1, len(data))}] = {{"]
if data:
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
else:
    lines.append('    0')
lines.append('};')
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write('\n'.join(lines) + '\n')
print(f"{len(names)} bank file(s), {len(data)} bytes")
