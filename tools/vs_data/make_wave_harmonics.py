"""Generates vs_wave_harmonics.txt: the waves of the Prophet VS as a harmonic table.

One-off tool for the project maintainer; if you only build the engine you do
not need it. It reads the waves 32..125 from a ROM image (OS r1.2) and
describes each one as a sum of harmonics:

  * magnitude of each harmonic rounded to a 0.5 dB grid, relative to the
    strongest harmonic of the wave; everything below -60 dB is dropped
  * phase of each harmonic snapped to multiples of 90 degrees, after the wave
    has been shifted by a common time offset (grid 1/8 sample)
  * the DC component is dropped

The table is thus a smoothed description of the timbres, not a copy of the
sample values; it is, however, derived from the waves of the ROM.
gen_data.py computes the wavetables from it at build time.

Usage: make_wave_harmonics.py [--rom FILE | --msb FILE --lsb FILE]
"""
import argparse
import os

import numpy as np

import gen_data as g

OUT = g.HARMONICS
STEP_DB, FLOOR_DB, SHIFT_STEP = 0.5, -60.0, 0.125


def analyse(w, max_shift=4):
    """12-bit wave -> (time offset, reference level in dBFS, [(harmonic, dB, quadrant)])"""
    X = np.fft.rfft(w / 2048.0)
    amp, ph = 2.0 * np.abs(X[1:64]) / 128.0, np.angle(X[1:64])
    if amp.max() <= 0:
        return 0.0, 0.0, []
    ref_db = round(20 * np.log10(amp.max()), 2)
    db = np.round(20 * np.log10(np.maximum(amp, 1e-12) / amp.max()) / STEP_DB) * STEP_DB
    keep = db >= FLOOR_DB
    h = np.arange(1, 64)
    weight = np.where(keep, 10 ** (db / 10), 0.0)
    best = None
    for s in np.arange(-max_shift, max_shift, SHIFT_STEP):
        p = ph + 2 * np.pi * h * s / 128
        quad = np.round(p / (np.pi / 2))
        err = float(np.sum(weight * np.angle(np.exp(1j * (p - quad * np.pi / 2))) ** 2))
        if best is None or err < best[0] - 1e-12:
            best = (err, s, quad.astype(int) % 4)
    _, shift, quad = best
    return float(shift), ref_db, [(int(k), float(db[k - 1]), int(quad[k - 1])) for k in h if keep[k - 1]]


def write_table(path, title, waves, max_shift=4):
    lines = [f"# {title} (generated by make_wave_harmonics.py).",
             "# Line: wave  time offset in samples  reference level in dBFS  then per harmonic number:dB:quadrant",
             "#   dB: magnitude relative to the reference level (0.5 dB grid, omitted below -60 dB)",
             "#   quadrant q: phase q*90 degrees",
             "# wave[n] = sum over the harmonics h of",
             "#   10^((ref+dB)/20) * cos(2*pi*h*(n - offset)/128 + q*90 degrees),  n = 0..127"]
    total = 0
    for n, w in waves:
        shift, ref_db, parts = analyse(w, max_shift)
        total += len(parts)
        lines.append(f'{n} {shift:g} {ref_db:.2f} ' + ' '.join(f'{k}:{d + 0.0:g}:{q}' for k, d, q in parts))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write('\n'.join(lines) + '\n')
    print(f'{path}: {len(waves)} waves, {total} harmonics')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--rom')
    ap.add_argument('--msb')
    ap.add_argument('--lsb')
    rom, src = g.load_rom(ap.parse_args())
    write_table(OUT, 'Waves 32..125 of the Prophet VS as a harmonic table',
                [(n, g.rom_wave(rom, n)) for n in range(32, 126)])
