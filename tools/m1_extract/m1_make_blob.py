"""Turn a local Korg M1 ROM set into something the firmware can embed.

    python3 tools/m1_extract/m1_make_blob.py <romdir> <outdir>

Writes into <outdir>:
    m1_pcm.bin        2 M samples, 16-bit signed little-endian (4 MiB)
    m1_blob.S         assembly that pulls it in with .incbin
    m1_rom_tables.h   every table the engine reads, as C++ (multisounds, drum
                      sounds, interpolation kernel, VDF coefficients, EG, MG,
                      velocity and pan tables, effect tables, factory programs,
                      combinations and drum kits)

The PCM is the M1's own: 16-bit linear, so it is only interleaved, nothing is
decoded. All tables come from the user's ROM files -- the OS (Rev 19), the
coefficient ROM IC30 and the factory ALL DATA dump. No ROM data is in this
repository; see instruments/PicoFaceM1/README.md.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from m1_rom import M1RomSet, RomError, load_preload  # noqa: E402

STUB = """// Generated by tools/m1_extract/m1_make_blob.py -- do not edit.
// The M1 ROM images live outside the repository; this file only points at the
// copy the configure step produced.
    .section .rodata
    .balign 4
    .global m1_pcm_blob
    .global m1_pcm_blob_end
m1_pcm_blob:
    .incbin "{pcm}"
m1_pcm_blob_end:
"""

# Linear offsets into the 128 KB Rev 19 image (offset 0 = E0000). Found by
# content against the tables the analysis located in the Plus+1 OS; each is
# unique in the image. DS = F75C, so DS:x is at 0x175C0 + x.
REV19 = dict(
    eg_rise=(0x10C22, 256),      # CS:1133 in the Plus+1 driver segment, u16
    eg_fall=(0x10E22, 256),      # CS:1333, u16
    vel_curve=(0x116AB, 256),    # CS:1BC3, u16, index 252 = unity
    mg_delay=(0x10B5A, 100),     # CS:106B, u16, added to the delay accumulator per update
    mg_int_p=(0x109CA, 100),     # CS:0EDB, u16, pitch MG depth 0..8191
    mg_int_f=(0x10A92, 100),     # CS:0FA3, u16, VDF MG depth 0..8068
    mg_freq=(0x175C0 + 0x738E, 100),    # DS:738E (Plus+1 DS:78CC), phase step per update
    pitch_s=(0x175C0 + 0x0616, 153),    # DS:0616, 4096 * 2^((k-128)/12)
    pitch_f=(0x175C0 + 0x0748, 128),    # DS:0748, 65536 * (2^(j/1536) - 1)
    pan_reg=(0x175C0 + 0x0854, 14),     # DS:0854, u16
    pan101=(0x175C0 + 0x8272, 101),     # DS:8272 (Plus+1 DS:86EA), Q9
    def_bal=(0x175C0 + 0x749C, 68),     # DS:749C (Plus+1 DS:79DA), bytes
    fw_def=(0x175C0 + 0x7502, 272),     # DS:7502 (Plus+1 DS:7A40), 34 x 8 bytes
    delay_start=(0x175C0 + 0x7230, 100),  # DS:7230 (Plus+1 DS:776E), u16 ticks
    eq_k=(0x175C0 + 0x8966, 5),         # Q13 shelf corners
    eq_gain=(0x175C0 + 0x8970, 13),     # Q15, 0..-12 dB
)


def u16s(img, off, n):
    return list(struct.unpack_from("<%dH" % n, img, off))


def s16s(img, off, n):
    return list(struct.unpack_from("<%dh" % n, img, off))


def carr(name, ctype, vals, per_line=16, fmt=str):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(fmt(v) for v in vals[i:i + per_line]) + ",")
    return "static const %s %s[%d] = {\n%s\n};\n" % (ctype, name, len(vals), "\n".join(lines))


def ff(v):
    s = repr(float(v))
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def fx_init(fx, rom):
    """C++ aggregate initialiser for m1::FxTables (see m1_fx.h)."""
    z = lambda n: [0.0] * n

    def g(d, k, n=None, default=None):
        v = d.get(k) if d else None
        if v is None:
            return default if default is not None else (z(n) if n else 0)
        return v

    def fl(v):
        return "{" + ", ".join(ff(x) for x in v) + "}"

    def il(v):
        return "{" + ", ".join(str(int(x)) for x in v) + "}"

    def fl2(v, a, b):
        if v is None:
            v = [[0.0] * b for _ in range(a)]
        return "{" + ", ".join(fl(r) for r in v) + "}"

    revs = []
    for t in range(6):
        d = (fx.get("rev") or [None] * 6)[t] or {}
        revs.append("{%s, %s, %s, %s, %s, %s, %s, %s, %s, %d, %d, %d, %d, %s}" % (
            fl(g(d, "g", 4)), fl(g(d, "comb_out", 8)), il(g(d, "ap_d", 4)), il(g(d, "comb_d", 4)),
            il(g(d, "tap_l", 4)), il(g(d, "tap_r", 4)), ff(g(d, "g_in")),
            fl2(d.get("fb"), 4, 98), fl2(d.get("damp"), 4, 100),
            int(g(d, "base_ap")), int(g(d, "base_erl")), int(g(d, "base_err")), int(g(d, "base_erc")),
            fl(g(d, "er_scale", 3))))
    ers = []
    for t in range(6, 9):
        d = (fx.get("er") or {}).get(t) if isinstance(fx.get("er"), dict) else None
        if d is None and isinstance(fx.get("er"), list):
            d = fx["er"][t - 6]
        d = d or {}
        ers.append("{%s, %s}" % (fl(g(d, "g", 4)), fl(g(d, "tg", 25))))
    ro = fx.get("rotary") or {}
    rot = "{%s, %d, %d, %d, %d, %d, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s}" % (
        ", ".join(ff(g(ro, k)) for k in ("c20", "c24", "c28", "c2c", "c30", "c38", "c40", "c44")),
        *(int(g(ro, k)) for k in ("h_fb_tap", "h_w", "h_fix", "h_base", "d_w", "d_base")),
        il(g(ro, "micL", 5)), il(g(ro, "micR", 5)),
        ff(g(ro, "g120")), ff(g(ro, "g124")), ff(g(ro, "g130")), ff(g(ro, "g134")),
        il(g(ro, "accel", 2)), il(g(ro, "slow", 21)), il(g(ro, "fast", 21)), fl(g(ro, "depth_k", 4)))
    sy = fx.get("sym") or {}
    sym = "{%s, %s, %s, %s, %s}" % (fl(g(sy, "mix2", 3)), il(g(sy, "baseL", 3)), il(g(sy, "baseR", 3)),
                                    il(g(sy, "inc", 2)), il(g(sy, "off", 3)))
    crs = []
    for t in (25, 26):
        src = fx.get("crev")
        d = (src.get(t) if isinstance(src, dict) else (src[t - 25] if src else None)) or {}
        crs.append("{%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %d, %d, %d}" % (
            fl(g(d, "g", 3)), fl(g(d, "ger", 2)), fl(g(d, "cout", 4)), il(g(d, "ap_d", 3)),
            il(g(d, "comb_d", 4)), il(g(d, "comb_tap", 4)), fl(g(d, "eq", 6)), ff(g(d, "g_in")),
            fl2(d.get("fb"), 4, 98), fl2(d.get("damp"), 4, 100),
            int(g(d, "base_ap")), int(g(d, "base_b", default=353)), int(g(d, "base_c"))))
    ce = fx.get("cer") or {}
    cer = "{%s, %s, %s, %s, %s}" % (fl(g(ce, "g", 4)), fl(g(ce, "tg", 25)), fl(g(ce, "T", 25)),
                                    fl(g(ce, "A", 4)), ff(g(ce, "g_in")))
    eqk = s16s(rom.os, *REV19["eq_k"])
    eqg = s16s(rom.os, *REV19["eq_gain"])
    parts = [
        "{" + ", ".join(revs) + "}",
        fl(g(fx, "dly_damp_a", 100)), fl(g(fx, "dly_damp_b", 100)),
        fl(g(fx, "wt", 0x102 + 130)), fl(g(fx, "wt2", 130)), il(g(fx, "lfo_inc", 217)),
        "{" + ", ".join(ers) + "}", fl(g(fx, "er_T", 25)), fl(g(fx, "er_A", 4)),
        ff(g(fx, "trem_shape_k")), ff(g(fx, "exc_k")),
        rot, sym, "{" + ", ".join(crs) + "}", cer, il(eqk), il(eqg),
    ]
    return "static const m1::FxTables kFx = {\n    " + ",\n    ".join(parts) + "\n};\n"


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    romdir, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    try:
        rom = M1RomSet(romdir)
    except RomError as e:
        print("ERROR:", e, file=sys.stderr)
        return 1
    if not rom.preload_path:
        print("ERROR: no M1 ALL DATA dump (*.syx) in", romdir, file=sys.stderr)
        return 1
    pre = load_preload(rom.preload_path)
    img = rom.os

    # Sanity checks on the located tables: they have to look like what they are.
    eqk = s16s(img, *REV19["eq_k"])
    if eqk[:3] != [-7790, -7407, -6690]:
        print("ERROR: shelf table not where Rev 19 has it -- is this the Rev 19 OS?", file=sys.stderr)
        return 1
    pan101 = u16s(img, *REV19["pan101"])
    if pan101[0] != 0 or pan101[100] != 511 or pan101[50] != 360:
        print("ERROR: balance table not where Rev 19 has it", file=sys.stderr)
        return 1

    checks = [(u16s(img, *REV19["vel_curve"])[252], 15629, "velocity curve"),
              (u16s(img, *REV19["pitch_s"])[128], 4096, "pitch table"),
              (u16s(img, *REV19["mg_int_p"])[99], 8191, "pitch MG depth table"),
              (u16s(img, REV19["eg_rise"][0], 1)[0] > 0, True, "EG rise table")]
    for got, want, what in checks:
        if got != want:
            print("ERROR: %s not where Rev 19 has it (%r != %r)" % (what, got, want), file=sys.stderr)
            return 1

    with open(os.path.join(outdir, "m1_pcm.bin"), "wb") as f:
        f.write(rom.pcm)
    with open(os.path.join(outdir, "m1_blob.S"), "w") as f:
        f.write(STUB.format(pcm=os.path.join(os.path.abspath(outdir), "m1_pcm.bin")))

    mss = rom.multisounds()
    splits, msrows = [], []
    for m in mss:
        msrows.append('{%d, %d, %d, "%s"}' % (len(splits), len(m["splits"]), int(m["dwgs"]),
                                              m["name"].replace('"', "'")))
        for s in m["splits"]:
            splits.append("{%d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d}" % (
                s["start"], s["loop"], s["end"], s["tune128"], s["top"], s["pan"], s["root"],
                (1 if s["loop_on"] else 0) | (2 if s["nt"] else 0), s["tune"], s["level"],
                s["cutoff"], s["decay"]))

    drums = rom.drum_sounds()
    drows = ["{0, 0, 0, 0, 0}"] + ["{%d, %d, %d, %d, %d}" % (
        d["start"], d["loop"], d["end"], d["tune128"], 1 if d["loop_on"] else 0) for d in drums]

    try:
        from m1_fx_tables import fx_tables, UNRESOLVED
        fx = fx_tables(img)
        unresolved = sorted(UNRESOLVED)
    except ImportError:
        fx, unresolved = {}, ["(m1_fx_tables.py missing: all effect tables)"]
    except Exception as e:   # TEMPORARY while m1_fx_tables.py is being written
        fx, unresolved = {}, ["(m1_fx_tables.py failed: %s)" % e]

    k1, k2 = rom.vdf_k()
    kern = list(rom.kernel_bytes())
    h = ["// Generated by tools/m1_extract/m1_make_blob.py -- do not edit.",
         "// Tables read from the user's M1 ROM files; nothing here is in the repository.",
         "#pragma once", "#include <stdint.h>", '#include "m1_engine/m1_engine.h"', "",
         "namespace m1rom {", ""]
    h.append("static const m1::Multisound kMultisounds[100] = {\n    " + ",\n    ".join(msrows) + "\n};\n")
    h.append("static const m1::Split kSplits[%d] = {\n    " % len(splits) + ",\n    ".join(splits) + "\n};\n")
    h.append("static const int kDrumCount = %d;\n" % len(drums))
    h.append("static const m1::DrumSound kDrums[%d] = {\n    " % len(drows) + ",\n    ".join(drows) + "\n};\n")
    h.append(carr("kKernel", "uint8_t", kern, 32))
    h.append(carr("kVdf1k", "uint16_t", k1))
    h.append(carr("kVdf2k", "uint16_t", k2))
    for name, key in (("kEgRise", "eg_rise"), ("kEgFall", "eg_fall"), ("kVelCurve", "vel_curve"),
                      ("kMgFreq", "mg_freq"), ("kMgDelay", "mg_delay"), ("kMgIntP", "mg_int_p"),
                      ("kMgIntF", "mg_int_f"), ("kPitchS", "pitch_s"), ("kPitchF", "pitch_f"),
                      ("kPanReg", "pan_reg"), ("kPan101", "pan101"),
                      ("kDelayStart", "delay_start")):
        h.append(carr(name, "uint16_t", u16s(img, *REV19[key])))
    h.append(fx_init(fx, rom))
    h.append(carr("kPrograms", "uint8_t", [b for p in pre["programs"] for b in p], 32))
    h.append(carr("kCombis", "uint8_t", [b for c in pre["combis"] for b in c], 32))
    h.append(carr("kKits", "uint8_t", [b for k in pre["kits"] for b in k], 30))
    h.append("// Effect tables not found in the OS ROM (bypassed in the engine):")
    h.append("static const char* const kFxUnresolved = \"%s\";" % ", ".join(unresolved))
    h.append("\n}  // namespace m1rom\n")
    with open(os.path.join(outdir, "m1_rom_tables.h"), "w") as f:
        f.write("\n".join(h))

    print("m1_pcm.bin (4 MiB), m1_blob.S, m1_rom_tables.h: %d multisounds, %d splits, "
          "%d drum sounds, OS %s+%s, preload %s%s" % (
              len(mss), len(splits), len(drums), rom.os_files[0], rom.os_files[1],
              os.path.basename(rom.preload_path),
              ("; UNRESOLVED effect tables: " + ", ".join(unresolved)) if unresolved else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
